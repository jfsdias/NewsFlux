import { useEffect, useRef } from "react"

import {
  getContinuityResetRevision,
  readingContinuityState,
  saveReadingContinuity,
} from "@/store/readingContinuityState"
import { continuityFingerprint } from "@/utils/continuity-fingerprint"
import {
  canCaptureReaderScroll,
  clampReaderPosition,
  findReaderPosition,
} from "@/utils/reader-position"

// Reader content is hashed locally; only the digest and a bounded offset are persisted.
export default function useReaderContinuity({
  identityKey,
  entryId,
  content,
  pending,
  scrollRef,
  scrollMode,
  sessionRevision,
}) {
  const restoredArticleRef = useRef(null)
  useEffect(() => {
    const node = scrollRef.current?.getScrollElement()
    if (
      !node ||
      !identityKey ||
      !Number.isSafeInteger(entryId) ||
      entryId <= 0 ||
      pending ||
      !content
    ) {
      return
    }

    let active = true
    let ready = false
    let interrupted = false
    let gesture = null
    let account
    let scope
    let frame
    let timer
    const markInteraction = (event) => {
      if (!event.isTrusted || (event.type === "pointermove" && !event.buttons)) {
        return
      }
      interrupted = true
      gesture = { revision: getContinuityResetRevision(), at: Date.now() }
    }
    const save = () => {
      if (
        ready &&
        active &&
        canCaptureReaderScroll(gesture, getContinuityResetRevision(), Date.now())
      ) {
        saveReadingContinuity({
          account,
          entryId,
          scope,
          kind: "reader",
          offset: Math.max(0, Math.min(10_000_000, node.scrollTop)),
        })
      }
    }
    for (const event of [
      "wheel",
      "touchstart",
      "touchmove",
      "pointerdown",
      "pointermove",
      "keydown",
    ]) {
      node.addEventListener(event, markInteraction, { passive: true })
    }
    node.addEventListener("scroll", save, { passive: true })
    void Promise.all([continuityFingerprint(identityKey), continuityFingerprint(content)])
      .then(([accountHash, contentHash]) => {
        if (!active || !accountHash || !contentHash) {
          return null
        }
        account = accountHash
        scope = contentHash
        const articleKey = JSON.stringify([account, entryId])
        const shouldRestore = restoredArticleRef.current !== articleKey
        restoredArticleRef.current = articleKey
        const restore = () => {
          if (!active) {
            return
          }
          const position = shouldRestore
            ? findReaderPosition(readingContinuityState.get().records, account, entryId, scope)
            : null
          if (!interrupted && position !== null) {
            node.scrollTop = clampReaderPosition(position, node.scrollHeight, node.clientHeight)
          }
          // Ignore the scroll generated by restoration itself.
          timer = globalThis.setTimeout(() => {
            if (active) {
              ready = true
            }
          }, 0)
        }
        // ContentContext resets the reader after the next paint when opening an article.
        // Restore after that reset so it cannot erase the saved position.
        if (typeof globalThis.requestAnimationFrame === "function") {
          frame = globalThis.requestAnimationFrame(() => {
            frame = globalThis.requestAnimationFrame(restore)
          })
        } else {
          timer = globalThis.setTimeout(restore, 0)
        }
        return null
      })
      .catch(() => {})
    return () => {
      active = false
      node.removeEventListener("scroll", save)
      for (const event of [
        "wheel",
        "touchstart",
        "touchmove",
        "pointerdown",
        "pointermove",
        "keydown",
      ]) {
        node.removeEventListener(event, markInteraction)
      }
      if (frame !== undefined) {
        globalThis.cancelAnimationFrame(frame)
      }
      if (timer !== undefined) {
        globalThis.clearTimeout(timer)
      }
    }
  }, [identityKey, entryId, content, pending, scrollRef, scrollMode, sessionRevision])
}
